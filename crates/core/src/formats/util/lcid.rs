/// The locale name of `lcid`, if it is a common one.
pub fn name(lcid: u32) -> Option<&'static str> {
    lookup(LCIDS, lcid.into())
}

/// `0x0424 (sl-SI)`, or just the hex value for an unknown LCID.
pub fn describe(lcid: u32) -> String {
    match name(lcid) {
        Some(n) => format!("{lcid:#06x} ({n})"),
        None => format!("{lcid:#06x}"),
    }
}
