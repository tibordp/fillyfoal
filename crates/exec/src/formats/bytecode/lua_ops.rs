/// The table for a version byte (`0x50` to `0x55`).
pub fn table(version: u8) -> Table {
    match version {
        0x50 => LUA50,
        0x51 => LUA51,
        0x52 => LUA52,
        0x53 => LUA53,
        0x54 => LUA54,
        _ => LUA55,
    }
}
