/// The name of a call frame instruction (its first byte).
pub(crate) fn cfa_name(op: u8) -> String {
    match op >> 6 {
        1 => "DW_CFA_advance_loc".to_owned(),
        2 => "DW_CFA_offset".to_owned(),
        3 => "DW_CFA_restore".to_owned(),
        _ => crate::formats::util::val::name_or(CFA, op.into(), "DW_CFA"),
    }
}
