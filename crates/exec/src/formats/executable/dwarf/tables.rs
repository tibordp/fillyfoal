/// The name of a DWARF expression operation.
pub(super) fn op_name(op: u8) -> String {
    match op {
        0x30..=0x4f => format!("DW_OP_lit{}", op.saturating_sub(0x30)),
        0x50..=0x6f => format!("DW_OP_reg{}", op.saturating_sub(0x50)),
        0x70..=0x8f => format!("DW_OP_breg{}", op.saturating_sub(0x70)),
        _ => crate::formats::util::val::name_or(OPS, op.into(), "DW_OP"),
    }
}

