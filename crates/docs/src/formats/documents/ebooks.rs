/// EXTH records holding a big-endian u32 (calibre's MOBI writer and the
/// MobileRead wiki): sample, start reading, KF8 boundary, resource count,
/// 131, cover and thumbnail offsets, fake cover, creator software and
/// version. Everything else is text (501 is "EBOK", "PDOC", ...).
const EXTH_NUMERIC: &[u32] = &[115, 116, 121, 125, 131, 201, 202, 203, 204, 205, 206, 207];

async fn palm(cx: Cx, input: Input) -> Result<()> {
    let file = input.span;
    let h: PalmHeader = read_record(&cx, file.sub(0, PalmHeader::SIZE), BE).await?;
    cx.emit(PalmHeader::node(
        "Database header",
        file.sub(0, PalmHeader::SIZE),
        BE,
    ));
    let list = file.sub_exact(PalmHeader::SIZE, u64::from(h.records).saturating_mul(8))?;
    let entries = cx.read(list).await?;
    let offsets: Vec<u64> = (0..usize::from(h.records))
        .map(|i| u64::from(u32_be(&entries, i.saturating_mul(8)).unwrap_or(0)))
        .collect();
    cx.emit(
        Node::new("Records")
            .span(list)
            .summary(plural(h.records, "record"))
            .lazy(palm_records, (input, offsets.clone())),
    );
    let tag = format!("{}{}", h.kind, h.creator);
    let kind = PALM_KINDS
        .iter()
        .find(|(t, _)| t.starts_with(tag.as_bytes()))
        .map_or("Palm database", |(_, n)| n);
    let mut summary = format!("{kind}: {:?}", h.name);
    // Record 0 of PalmDOC/MOBI books holds the PalmDOC (and MOBI) header.
    if (tag == "BOOKMOBI" || tag == "TEXtREAd")
        && let (Some(&start), Some(&end)) = (offsets.first(), offsets.get(1).or(Some(&file.len)))
    {
        let record0 = file.sub(start, end.saturating_sub(start));
        let mut node = Node::new("Book header")
            .span(record0)
            .lazy(book_header_node, record0);
        if let Some(title) = mobi_title(&cx, record0).await? {
            summary = format!("{kind}: {title:?}");
            node = node.summary(title);
        }
        cx.emit(node);
        cx.emit(book_text(&cx, input, record0, &offsets).await?);
        // A combined MOBI 6 + KF8 file: EXTH 121 names the record 0 of the
        // KF8 half (after a "BOUNDARY" record), which has its own headers,
        // text records and record numbering.
        if let Some(k) = kf8_boundary(&cx, record0).await?
            && let Some(kf8) = offsets.get(k..).filter(|o| o.len() > 1)
            && let Some(&start) = kf8.first()
        {
            let end = kf8.get(1).copied().unwrap_or(file.len);
            let kf8_record0 = file.sub(start, end.saturating_sub(start));
            let mut node = Node::new("KF8 book header")
                .span(kf8_record0)
                .summary(format!("record {k}"))
                .lazy(book_header_node, kf8_record0);
            let boundary = match k.checked_sub(1).and_then(|b| offsets.get(b)) {
                Some(&b) => cx.read_avail(file.sub(b, 8)).await?,
                None => Vec::new(),
            };
            if boundary != b"BOUNDARY" {
                node = node.diag(Diagnostic::warning(
                    "the record before the KF8 header is not BOUNDARY",
                ));
            }
            cx.emit(node);
            cx.emit(
                book_text(&cx, input, kf8_record0, kf8)
                    .await?
                    .renamed("KF8 text"),
            );
            summary = format!("{summary}, with a KF8 part");
        }
    }
    cx.annotate(summary);
    Ok(())
}

/// The book's text: the text records after record 0, without their
/// trailing entries, decompressed and joined.
async fn book_text(cx: &Cx, input: Input, record0: Span, offsets: &[u64]) -> Result<Node> {
    use crate::codec::Codec;
    use crate::codec::palmdoc::Book;
    let head = cx.read_avail(record0.sub(0, 0xf4)).await?;
    let compression = u16_be(&head, 0).unwrap_or(0);
    let length = u64::from(u32_be(&head, 4).unwrap_or(0));
    let count = usize::from(u16_be(&head, 8).unwrap_or(0));
    let encryption = u16_be(&head, 12).unwrap_or(0);
    // The MOBI header's extra data flags, if it is long enough to have
    // them (from header length 0xE4, at 0xF2 in record 0).
    let mobi = head.get(16..20) == Some(b"MOBI");
    let header_len = u32_be(&head, 20).unwrap_or(0);
    let trailing = if mobi && header_len >= 0xe4 {
        u16_be(&head, 0xf2).unwrap_or(0)
    } else {
        0
    };
    let first = offsets.get(1).copied().unwrap_or(input.span.len);
    let end = offsets
        .get(count.saturating_add(1))
        .copied()
        .unwrap_or(input.span.len);
    let span = input.span.sub(first, end.saturating_sub(first));
    let node = Node::new("Text").span(span);
    let records: Option<Vec<u32>> = (1..=count)
        .map(|i| {
            let start = *offsets.get(i)?;
            let next = offsets
                .get(i.saturating_add(1))
                .copied()
                .unwrap_or(input.span.len);
            u32::try_from(next.checked_sub(start)?).ok()
        })
        .collect();
    let Some(records) = records.filter(|r| !r.is_empty()) else {
        return Ok(node.diag(Diagnostic::malformed(
            "text records missing or out of order",
        )));
    };
    if encryption != 0 && mobi {
        return Ok(node.diag(Diagnostic::unsupported("encrypted Mobipocket text")));
    }
    let compressed = match compression {
        1 => false,
        2 => true,
        17480 => return Ok(node.diag(Diagnostic::unsupported("HUFF/CDIC compression"))),
        c => return Ok(node.diag(Diagnostic::unsupported(format!("text compression {c}")))),
    };
    let codec = Codec::PalmDoc(Book {
        records: records.into(),
        trailing,
        compressed,
    });
    Ok(
        crate::formats::content("Text", input, span, codec, Some(length)).summary(format!(
            "{length} bytes in {count_record}",
            count_record = plural(count, "record")
        )),
    )
}

async fn palm_records(cx: Cx, (input, offsets): (Input, Vec<u64>)) -> Result<()> {
    cx.set_count(Count::Exact(crate::bytes::to_u64(offsets.len())));
    for (i, &start) in offsets.iter().enumerate() {
        let end = offsets
            .get(i.saturating_add(1))
            .copied()
            .unwrap_or(input.span.len);
        if end < start {
            cx.push(
                Node::new(format!("Record {i}"))
                    .diag(Diagnostic::malformed("record offsets out of order")),
            )
            .await;
            continue;
        }
        let span = input.span.sub(start, end.saturating_sub(start));
        // Records are mostly compressed text or images: shown as data
        // unless a format is recognised.
        cx.push(
            Node::new(format!("Record {i}"))
                .span(span)
                .summary(format!("{} bytes", span.len))
                .lazy(crate::formats::dissect_or_data, input.nested(span)),
        )
        .await;
    }
    Ok(())
}

/// The full title from the MOBI header of record 0, if there is one.
async fn mobi_title(cx: &Cx, record0: Span) -> Result<Option<String>> {
    let mobi = cx.read_avail(record0.sub(16, 0x4c)).await?;
    if !mobi.starts_with(b"MOBI") {
        return Ok(None);
    }
    let offset = u64::from(u32_be(&mobi, 0x44).unwrap_or(0));
    let len = u64::from(u32_be(&mobi, 0x48).unwrap_or(0));
    let title = cx.read_avail(record0.sub(offset, len.min(1024))).await?;
    Ok(Some(String::from_utf8_lossy(&title).into_owned()))
}

/// The value of EXTH 121 (the KF8 record 0's record number) in a MOBI 6
/// record 0, if there is one and it is not the KF8 header itself.
async fn kf8_boundary(cx: &Cx, record0: Span) -> Result<Option<usize>> {
    let mobi = cx.read_avail(record0.sub(16, 0x18)).await?;
    if !mobi.starts_with(b"MOBI") || u32_be(&mobi, 0x14).unwrap_or(0) >= 8 {
        return Ok(None);
    }
    let flags = cx.read_avail(record0.sub(0x80, 4)).await?;
    if u32_be(&flags, 0).unwrap_or(0) & 0x40 == 0 {
        return Ok(None);
    }
    let header_len = u64::from(u32_be(&mobi, 4).unwrap_or(0));
    // EXTH lives inside record 0, which stays small; 64 KiB is plenty.
    let exth = cx
        .read_avail(
            record0
                .tail(16u64.saturating_add(header_len))
                .sub(0, 0x10000),
        )
        .await?;
    if !exth.starts_with(b"EXTH") {
        return Ok(None);
    }
    let count = u32_be(&exth, 8).unwrap_or(0);
    let mut at = 12usize;
    for _ in 0..count {
        let (Some(kind), Some(len)) = (u32_be(&exth, at), u32_be(&exth, at.saturating_add(4)))
        else {
            break;
        };
        if kind == 121 && len == 12 {
            return Ok(u32_be(&exth, at.saturating_add(8))
                .filter(|&v| v != NULL_INDEX && v > 0)
                .and_then(|v| usize::try_from(v).ok()));
        }
        if len < 8 {
            break;
        }
        at = at.saturating_add(usize::try_from(len).unwrap_or(usize::MAX));
    }
    Ok(None)
}

async fn book_header_node(cx: Cx, record0: Span) -> Result<()> {
    book_header(&cx, record0).await.map(|_| ())
}

/// Emits the PalmDOC header, the MOBI header and EXTH metadata of record 0.
/// Returns the full title if present.
async fn book_header(cx: &Cx, record0: Span) -> Result<Option<String>> {
    let block = cx.block(record0.sub(0, 16)).await?;
    {
        let mut f = Fields::emitting(cx, &block, BE);
        // Not lazy: these few fields are the book's identity.
        f.u16("Compression")
            .enumeration(PALMDOC_COMPRESSION)
            .emit()?;
        f.u16("Unused").emit()?;
        f.u32("Text length").emit()?;
        f.u16("Text record count").emit()?;
        f.u16("Text record size").emit()?;
        f.u16("Encryption")
            .enumeration(&[(0, "none"), (1, "old Mobipocket"), (2, "Mobipocket")])
            .emit()?;
        f.u16("Unknown").emit()?;
    }
    let mobi = cx.read_avail(record0.sub(16, 0x100)).await?;
    if !mobi.starts_with(b"MOBI") {
        return Ok(None);
    }
    let header_len = u64::from(u32_be(&mobi, 4).unwrap_or(0));
    let mobi_span = record0.sub(16, header_len);
    let kind = u32_be(&mobi, 8).unwrap_or(0);
    let encoding = u32_be(&mobi, 12).unwrap_or(0);
    let version = u32_be(&mobi, 0x14).unwrap_or(0);
    let title_offset = u64::from(u32_be(&mobi, 0x44).unwrap_or(0));
    let title_len = u64::from(u32_be(&mobi, 0x48).unwrap_or(0));
    let exth_flags = u32_be(&mobi, 0x70).unwrap_or(0);
    cx.emit(
        struct_node("MOBI header", mobi_span, BE, header_len, mobi_header_layout).summary(format!(
            "{}, version {version}, {}",
            lookup(MOBI_TYPES, kind.into()).unwrap_or("unknown type"),
            lookup(TEXT_ENCODINGS, encoding.into()).unwrap_or("unknown encoding"),
        )),
    );
    if exth_flags & 0x40 != 0 {
        let exth = record0.tail(16u64.saturating_add(header_len));
        cx.emit(
            Node::new("EXTH metadata")
                .span(exth)
                .lazy(exth_records, exth),
        );
    }
    let title_span = record0.sub(title_offset, title_len);
    let title = String::from_utf8_lossy(&cx.read_avail(title_span).await?).into_owned();
    cx.emit(
        Node::new("Full name")
            .span(title_span)
            .value(Value::Text(title.clone())),
    );
    Ok(Some(title))
}

const TEXT_ENCODINGS: EnumTable = &[(1252, "CP1252"), (65001, "UTF-8")];

const EXTRA_DATA_FLAGS: FlagTable = &[
    flag(0x1, "multibyte characters"),
    flag(0x2, "TBS indexing"),
    flag(0x4, "uncrossable breaks"),
];

const EXTH_FLAGS: FlagTable = &[flag(0x40, "EXTH present")];

/// "No record" in the MOBI header's record numbers.
const NULL_INDEX: u32 = u32::MAX;

/// A record number in the MOBI header. In the KF8 half of a combined file
/// they count from that half's record 0 (calibre's `relative_records`).
fn record_index(&v: &u32, node: Node) -> Node {
    if v == NULL_INDEX {
        node.summary("none")
    } else {
        node
    }
}

/// The MOBI header after the 16-byte PalmDOC header of record 0, field by
/// field as calibre 6.13 reads it (`ebooks/mobi/debug/headers.py`,
/// `MOBIHeader`, whose offsets count from record 0 and ours from "MOBI").
/// Later groups are there only when the header is long enough for them.
fn mobi_header_layout(f: &mut Fields<'_>, &header_len: &u64) -> Result<()> {
    f.ascii("Identifier", 4).emit()?;
    f.u32("Header length").emit()?;
    f.u32("Type").enumeration(MOBI_TYPES).emit()?;
    f.u32("Text encoding").enumeration(TEXT_ENCODINGS).emit()?;
    f.u32("Unique ID").hex().emit()?;
    let version = f.u32("File version").emit()?;
    f.u32("Meta orthographic index")
        .with(record_index)
        .desc("In KF8: the fragment (section) index")
        .emit()?;
    f.u32("Meta inflection index").with(record_index).emit()?;
    f.u32("Secondary index record").with(record_index).emit()?;
    f.bytes("Reserved", 28).emit()?;
    f.u32("First non-book record").with(record_index).emit()?;
    f.u32("Full name offset").hex().emit()?;
    f.u32("Full name length").emit()?;
    f.u32("Locale")
        .hex()
        .desc("Language ID in the low byte, sublanguage in bits 10-17")
        .emit()?;
    f.u32("Input language").hex().emit()?;
    f.u32("Output language").hex().emit()?;
    f.u32("Minimum reader version").emit()?;
    f.u32("First image record").with(record_index).emit()?;
    f.u32("Huffman record").with(record_index).emit()?;
    f.u32("Huffman record count").emit()?;
    f.u32("Huffman table offset")
        .with(record_index)
        .desc("In KF8: the DATP record")
        .emit()?;
    f.u32("Huffman table length").emit()?;
    f.u32("EXTH flags").hex().flags(EXTH_FLAGS).emit()?;
    if header_len < 168 {
        return Ok(());
    }
    f.bytes("Unknown", 36).emit()?;
    f.u32("DRM offset").with(record_index).emit()?;
    f.u32("DRM count").emit()?;
    f.u32("DRM size").emit()?;
    f.u32("DRM flags").hex().emit()?;
    if header_len < 232 {
        return Ok(());
    }
    f.bytes("Unknown", 8).emit()?;
    if version < 8 {
        f.u16("First text record").emit()?;
        f.u16("Last text record").emit()?;
        f.u32("Unknown").hex().emit()?;
    } else {
        f.u32("FDST record").with(record_index).emit()?;
        f.u32("FDST count").emit()?;
    }
    f.u32("FCIS record").with(record_index).emit()?;
    f.u32("FCIS count").emit()?;
    f.u32("FLIS record").with(record_index).emit()?;
    f.u32("FLIS count").emit()?;
    f.bytes("Unknown", 8).emit()?;
    f.u32("SRCS record").with(record_index).emit()?;
    f.u32("SRCS count").emit()?;
    f.bytes("Unknown", 8).emit()?;
    f.u32("Extra data flags")
        .hex()
        .flags(EXTRA_DATA_FLAGS)
        .desc("Trailing entries at the end of each text record")
        .emit()?;
    f.u32("Primary index record")
        .with(record_index)
        .desc("The NCX index (INDX)")
        .emit()?;
    if header_len < 248 {
        return Ok(());
    }
    f.u32("Fragment index").with(record_index).emit()?;
    f.u32("Skeleton index").with(record_index).emit()?;
    f.u32("DATP record").with(record_index).emit()?;
    f.u32("Guide index").with(record_index).emit()?;
    let rest = header_len.saturating_sub(f.pos());
    if rest > 0 {
        f.bytes("Unknown", rest).emit()?;
    }
    Ok(())
}

async fn exth_records(cx: Cx, span: Span) -> Result<()> {
    let mut cur = Cursor::new(&cx, span, BE);
    let magic = cur.bytes(4).await?;
    if magic != b"EXTH" {
        return Err(Diagnostic::malformed("missing EXTH magic").at(span.sub(0, 4)));
    }
    let _len = cur.u32().await?;
    let count = cur.u32().await?;
    cx.set_count(Count::Exact(count.into()));
    for _ in 0..count {
        let start = cur.pos();
        let kind = cur.u32().await?;
        let len = cur.u32().await?;
        let data_len = u64::from(len.saturating_sub(8));
        let data = cur.bytes(data_len).await?;
        let name = lookup(EXTH, kind.into()).map_or_else(|| format!("EXTH {kind}"), str::to_owned);
        let value = if data_len == 4 && EXTH_NUMERIC.contains(&kind) {
            Value::UInt {
                value: u32_be(&data, 0).unwrap_or(0).into(),
                bits: 32,
                radix: crate::value::Radix::Dec,
            }
        } else {
            Value::Text(String::from_utf8_lossy(&data).into_owned())
        };
        cx.push(Node::new(name).span(cur.since(start)).value(value))
            .await;
    }
    Ok(())
}

// ---------------------------------------------------------------------------
// Microsoft Reader (LIT)

declare_format!(pub LIT = "lit", "Microsoft Reader e-book", ["lit"], "application/x-ms-reader",
    Probe::Magic(&[(0, b"ITOLITLS")]), lit);

record! {
    pub struct LitHeader {
        magic: ascii[8] "Magic",
        version: u32 "Version",
        header_len: u32 "Header length" .hex(),
        pieces: u32 "Number of pieces",
        secondary_len: u32 "Secondary header length" .hex(),
        guid: guid "Header GUID",
    }
}

async fn lit(cx: Cx, input: Input) -> Result<()> {
    let file = input.span;
    let h: LitHeader = read_record(
        &cx,
        file.sub(0, LitHeader::SIZE),
        crate::fields::Endian::Little,
    )
    .await?;
    cx.emit(LitHeader::node(
        "Header",
        file.sub(0, LitHeader::SIZE),
        crate::fields::Endian::Little,
    ));
    let table = file.sub(h.header_len.into(), u64::from(h.pieces).saturating_mul(16));
    let entries = cx.read_avail(table).await?;
    for i in 0..usize::try_from(h.pieces.min(64)).unwrap_or(0) {
        let at = i.saturating_mul(16);
        let offset = crate::bytes::u64_le(&entries, at).unwrap_or(0);
        let size = crate::bytes::u64_le(&entries, at.saturating_add(8)).unwrap_or(0);
        cx.push(
            Node::new(format!("Piece {i}"))
                .span(file.sub(offset, size))
                .summary(format!("{size} bytes")),
        )
        .await;
    }
    cx.annotate(format!(
        "Microsoft Reader, version {}, {}",
        h.version,
        plural(h.pieces, "piece")
    ));
    Ok(())
}
