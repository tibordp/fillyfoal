/// Known (type, creator) pairs at offset 60.
const PALM_KINDS: &[(&[u8; 8], &str)] = &[
    (b"BOOKMOBI", "Mobipocket e-book"),
    (b"TEXtREAd", "PalmDOC e-book"),
    (b"PNRdPPrs", "eReader e-book"),
    (b"DataPlkr", "Plucker document"),
    (b"ToGoToGo", "iSilo document"),
    (b"SDocSilX", "iSilo 3 document"),
    (b"BVokBDIC", "BDicty dictionary"),
    (b"DB99DBOS", "DB database"),
    (b"JbDbJBas", "JFile database"),
];

fn palm_kind(h: &Head<'_>) -> Option<&'static str> {
    let tag = h.data.get(60..68)?;
    PALM_KINDS
        .iter()
        .find(|(t, _)| tag == &t[..])
        .map(|(_, n)| *n)
}

fn mobi_probe(h: &Head<'_>) -> bool {
    h.at(60, b"BOOKMOBI")
}

fn palmdoc_probe(h: &Head<'_>) -> bool {
    h.at(60, b"TEXtREAd")
}

/// A generic Palm database: a 78-byte header and a record list whose
/// offsets are increasing and within the file.
fn pdb_probe(h: &Head<'_>) -> bool {
    let d = h.data;
    let records = u16_be(d, 76).unwrap_or(0);
    let name_ok = d.get(..32).is_some_and(|n| {
        n.iter()
            .take_while(|&&b| b != 0)
            .all(|&b| (0x20..0x7f).contains(&b))
            && n.first().is_some_and(|&b| b != 0)
    });
    let type_ok = d
        .get(60..68)
        .is_some_and(|t| t.iter().all(|&b| (0x20..0x7f).contains(&b)));
    let first = u32_be(d, 78).unwrap_or(0);
    name_ok
        && type_ok
        && records > 0
        && u64::from(first) >= 78u64.saturating_add(u64::from(records).saturating_mul(8))
        && u64::from(first) < h.len
        && (palm_kind(h).is_some()
            || h.data
                .get(60..64)
                .is_some_and(|t| t.iter().all(u8::is_ascii_alphanumeric)))
}

