/// The name of a GPT partition type, given its canonical text form
/// (with or without braces, any case).
pub fn gpt_type(guid: &str) -> Option<&'static str> {
    let key = guid
        .trim_matches(|c| c == '{' || c == '}')
        .to_ascii_lowercase();
    GPT_TYPES.iter().find(|(g, _)| *g == key).map(|(_, n)| *n)
}
