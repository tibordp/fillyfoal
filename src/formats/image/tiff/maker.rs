//! Exif maker notes: where each camera maker's IFD starts, what its
//! offsets are relative to, and the names of the commonly used tags.
//!
//! Layouts and tag names follow the conventions documented by ExifTool
//! (Phil Harvey; distributed under the same terms as Perl, i.e. GPL-1.0+ or
//! Artistic) and exiv2 for the private directories; nothing is copied from
//! their code. The maker is chosen from the note's own header when it has
//! one, otherwise from the Make tag of IFD0.

use crate::fields::{Endian, Prim};
use crate::value::EnumTable;

/// The camera maker named by the Make tag.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Make {
    Unknown,
    Canon,
    Nikon,
    Sony,
    Fujifilm,
    Olympus,
    Panasonic,
    Apple,
    Pentax,
    Samsung,
}

pub fn make_of(make: &str) -> Make {
    let m = make.trim().to_ascii_uppercase();
    let starts = |p: &str| m.starts_with(p);
    if starts("CANON") {
        Make::Canon
    } else if starts("NIKON") {
        Make::Nikon
    } else if starts("SONY") {
        Make::Sony
    } else if starts("FUJIFILM") || starts("FUJI ") {
        Make::Fujifilm
    } else if starts("OLYMPUS") || starts("OM DIGITAL") {
        Make::Olympus
    } else if starts("PANASONIC") {
        Make::Panasonic
    } else if starts("APPLE") {
        Make::Apple
    } else if starts("PENTAX") || starts("RICOH") || starts("ASAHI") {
        Make::Pentax
    } else if starts("SAMSUNG") {
        Make::Samsung
    } else {
        Make::Unknown
    }
}

