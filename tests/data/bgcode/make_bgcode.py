"""Generates the G-code fixtures: a small PrusaSlicer-style text G-code
(written here, in the layout of PrusaSlicer 2.8 output) and its binary
conversions by libbgcode.

    uv run --no-project --with pillow \
        --with "pybgcode @ git+https://github.com/prusa3d/libbgcode@d4da9073616d70a43c151e8c1d7fbff879d2e08a" \
        python tests/data/bgcode/make_bgcode.py

Writes:
- tests/fixtures/synthetic/gcode/prusaslicer.gcode (the text source),
- tests/fixtures/external/bgcode/*.bgcode (libbgcode `from_ascii_to_binary`
  with each compression, G-code encoding and checksum type),
- tests/data/bgcode/*.ref.gcode (libbgcode `from_binary_to_ascii` of each,
  which the tests compare our decoded G-code blocks against).
"""

import base64
import io
import os

import pybgcode
from pybgcode import _bgcode
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
SYN = os.path.join(ROOT, "tests/fixtures/synthetic/gcode")
EXT = os.path.join(ROOT, "tests/fixtures/external/bgcode")
REF = os.path.join(ROOT, "tests/data/bgcode")


def thumbnail(fmt, size):
    im = Image.new("RGB", size, (240, 240, 240))
    for x in range(size[0] // 4, 3 * size[0] // 4):
        for y in range(size[1] // 4, 3 * size[1] // 4):
            im.putpixel((x, y), (250, 104, 49))
    out = io.BytesIO()
    im.save(out, fmt, **({"quality": 50} if fmt == "JPEG" else {}))
    return out.getvalue()


def thumbnail_block(tag, data, size):
    text = base64.b64encode(data).decode()
    lines = [f"; {tag} begin {size[0]}x{size[1]} {len(text)}"]
    lines += ["; " + text[i : i + 78] for i in range(0, len(text), 78)]
    lines += [f"; {tag} end", ";", ""]
    return lines


