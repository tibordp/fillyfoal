VARIANTS = [
    # name, metadata compression, G-code compression, encoding, checksum
    ("plain", "none", "none", "none", "none"),
    ("deflate", "Deflate", "Deflate", "none", "CRC32"),
    ("heatshrink-11", "Heatshrink_11_4", "Heatshrink_11_4", "MeatPack", "CRC32"),
    ("heatshrink-12", "none", "Heatshrink_12_4", "MeatPackComments", "CRC32"),
    ("meatpack", "none", "none", "MeatPack", "none"),
]


def main():
    for d in (SYN, EXT, REF):
        os.makedirs(d, exist_ok=True)
    src = os.path.join(SYN, "prusaslicer.gcode")
    with open(src, "w", newline="\n") as f:
        f.write(source())
    for name, meta, gcode, encoding, checksum in VARIANTS:
        cfg = pybgcode.get_config()
        c = pybgcode.CompressionType
        for field in ("file_metadata", "printer_metadata", "print_metadata", "slicer_metadata"):
            setattr(cfg.compression, field, getattr(c, meta))
        cfg.compression.gcode = getattr(c, gcode)
        cfg.gcode_encoding = getattr(_bgcode.GCodeEncodingType, encoding)
        cfg.checksum = getattr(_bgcode.ChecksumType, checksum)
        out = os.path.join(EXT, f"{name}.bgcode")
        i, o = pybgcode.open(src, "r"), pybgcode.open(out, "wb")
        res = pybgcode.from_ascii_to_binary(i, o, cfg)
        pybgcode.close(o)
        pybgcode.close(i)
        assert res == pybgcode.EResult.Success, (name, res)
        i, o = pybgcode.open(out, "rb"), pybgcode.open(os.path.join(REF, f"{name}.ref.gcode"), "w")
        res = pybgcode.from_binary_to_ascii(i, o, True)
        pybgcode.close(o)
        pybgcode.close(i)
        assert res == pybgcode.EResult.Success, (name, res)
        print(name, os.path.getsize(out))


main()
