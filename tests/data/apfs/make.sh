#!/bin/sh
# Builds tests/fixtures/external/apfs/tree.img.gz on macOS: a 4 MiB APFS
# container made by newfs_apfs (through hdiutil) and filled by the macOS
# APFS driver with
#   - hello.txt, docs/sub/deep/nested.txt: a directory tree;
#   - frag.bin: a 12-block file in several extents, made by punching holes
#     into a full volume first;
#   - sparse.bin: data, a 64 KiB hole, data;
#   - docs/words.dat: decmpfs-compressed by `ditto --hfsCompression` (LZVN
#     in com.apple.ResourceFork);
#   - a.txt and docs/hard.txt: one inode under two names;
#   - link: a symbolic link to hello.txt;
#   - xattr.txt: a small extended attribute and an 8 KiB one (kept in its
#     own data stream).
# Content is generated by ../hfsplus/content.py and here; names are
# neutral; Spotlight and fseventsd are kept out (`-nobrowse`,
# `.fseventsd/no_log`). The files record the numeric ids of the user who
# ran this (501/20 for the first macOS account). scrub.py then zeroes the
# app id in the com.apple.provenance attributes and fixes the checksums of
# the blocks it touched.
#
# Usage: sh tests/data/apfs/make.sh <output dir>
set -eu
here=$(cd "$(dirname "$0")" && pwd)
out=$(cd "${1:?output dir}" && pwd)
work=/tmp/fixtures/disk-b-apfs
mkdir -p "$work"
cd "$work"
test "$(pwd)" = "$work"
rm -f apfs.dmg
rm -rf src
mkdir src
python3 "$here/../hfsplus/content.py" src
hdiutil create -size 4m -fs APFS -volname fillyfoal -layout NONE apfs.dmg
hdiutil attach -nobrowse -noverify -noautoopen -mountpoint "$work/mnt" apfs.dmg
cd mnt
test "$(pwd)" = "$work/mnt"
mkdir -p .fseventsd
touch .fseventsd/no_log
i=0
while [ $i -lt 24 ]; do
    head -c 4096 /dev/zero > "gap$i"
    i=$((i + 1))
done
sync
avail=$(df -k . | awk 'NR==2 {print $4}')
head -c "$(( (avail - 64) * 1024 ))" /dev/zero > filler 2>/dev/null || true
sync
i=0
while [ $i -lt 24 ]; do
    rm "gap$i"
    i=$((i + 2))
done
sync
sleep 3
sync
cat ../src/frag.bin > frag.bin
sync
rm filler gap*
printf 'hello from APFS\n' > hello.txt
mkdir -p docs/sub/deep
printf 'nested file\n' > docs/sub/deep/nested.txt
printf 'start' > sparse.bin
printf 'end' | dd of=sparse.bin bs=1 seek=69632 conv=notrunc 2>/dev/null
ditto --hfsCompression ../src/words.dat docs/words.dat
printf 'one file, two names\n' > a.txt
ln a.txt docs/hard.txt
ln -s hello.txt link
printf 'has extended attributes\n' > xattr.txt
xattr -w org.example.note "a neutral attribute value" xattr.txt
xattr -w org.example.big "$(python3 -c 'print("0123456789abcdef" * 512, end="")')" xattr.txt
sync
cd "$work"
hdiutil detach "$work/mnt"
python3 "$here/scrub.py" apfs.dmg
gzip -9 -n -c apfs.dmg > "$out/tree.img.gz"
