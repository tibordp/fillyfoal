"""Turns the SPIR-V core grammar into the Rust tables of spirv_tables.rs.

Usage: python3 tables_gen.py spirv.core.grammar.json PACKAGE-VERSION
"""

import json
import sys


def enum_table(name, pairs, doc):
    out = [f"/// {doc}", f"pub const {name}: EnumTable = &["]
    seen = set()
    for value, label in sorted(pairs):
        if value in seen:
            continue  # aliases share a value; keep the first name
        seen.add(value)
        out.append(f'    ({value}, "{label}"),')
    out.append("];")
    return "\n".join(out)


def main():
    grammar = json.load(open(sys.argv[1]))
    version = sys.argv[2]
    ops = [(i["opcode"], i["opname"]) for i in grammar["instructions"]]
    kinds = {k["kind"]: k for k in grammar["operand_kinds"]}

    def kind(name):
        return [(int(e["value"]), e["enumerant"]) for e in kinds[name]["enumerants"]]

    print("//! SPIR-V names from the Khronos grammar (`spirv.core.grammar.json`,")
    print(f"//! Alpine `spirv-headers` {version}, SPIR-V "
          f"{grammar['major_version']}.{grammar['minor_version']} "
          f"revision {grammar['revision']}).")
    print("//!")
    print("//! Generated by `tests/data/spirv/make-tables.sh`; do not edit.")
    print()
    print("use crate::value::EnumTable;")
    print()
    print(enum_table("OPCODE", ops, "Instruction opcodes."))
    print()
    print(enum_table("CAPABILITY", kind("Capability"), "`OpCapability` operands."))
    print()
    print(enum_table("EXECUTION_MODEL", kind("ExecutionModel"), "`OpEntryPoint` execution models."))
    print()
    print(enum_table("SOURCE_LANGUAGE", kind("SourceLanguage"), "`OpSource` languages."))
    print()
    print(enum_table("ADDRESSING_MODEL", kind("AddressingModel"), "`OpMemoryModel` addressing models."))
    print()
    print(enum_table("MEMORY_MODEL", kind("MemoryModel"), "`OpMemoryModel` memory models."))


main()
