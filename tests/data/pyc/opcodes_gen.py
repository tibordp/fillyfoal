"""Turns the ops-X.Y.json files written by opcodes_dump.py (one per CPython
version) into crates/exec/src/formats/bytecode/pyc_ops.rs. Run by
make-opcodes.sh: python3 -I opcodes_gen.py DIR > pyc_ops.rs"""
import json
import os
import sys

d = sys.argv[1]
tables = []
for name in sorted(os.listdir(d), key=lambda n: [int(x) for x in n[4:-5].split(".")] if n.startswith("ops-") and n.endswith(".json") else [0]):
    if name.startswith("ops-") and name.endswith(".json"):
        tables.append(json.load(open(os.path.join(d, name))))

KINDS = [("const", 1), ("name", 2), ("local", 4), ("free", 8), ("jrel", 16), ("jabs", 32), ("compare", 64), ("jump", 128)]

out = []
w = out.append
w("//! CPython opcode tables per version, for the pyc disassembly.")
w("//!")
w("//! Generated by `tests/data/pyc/make-opcodes.sh` from each interpreter's")
w("//! own `dis` and `opcode` modules (Docker `python:X.Y-slim`); do not edit.")
w("")
w("/// One version's table.")
w("pub struct Ops {")
w("    pub version: (u8, u8),")
w("    /// Opcode names; empty for unused opcodes.")
w("    pub names: [&'static str; 256],")
w("    /// Inline cache code units after each opcode (3.11+).")
w("    pub caches: [u8; 256],")
w("    /// `K_*` argument kinds.")
w("    pub kinds: [u8; 256],")
w("    /// Opcodes at or above this take an argument (before 3.6).")
w("    pub have_argument: u8,")
w("    pub extended_arg: u8,")
w("    pub cmp_op: &'static [&'static str],")
w("}")
w("")
for k, bit in KINDS:
    w("pub const K_%s: u8 = %d;" % (k.upper(), bit))
w("")
w("pub static TABLES: &[Ops] = &[")


def strs(items):
    return ", ".join('"%s"' % s for s in items)


for t in tables:
    major, minor = t["version"].split(".")
    names = ["" if n.startswith("<") else n for n in t["names"]]
    kinds = [0] * 256
    for k, bit in KINDS:
        for op in t[k]:
            kinds[op] |= bit
    w("    Ops {")
    w("        version: (%s, %s)," % (major, minor))
    w("        names: [%s]," % strs(names))
    w("        caches: [%s]," % ", ".join(str(c) for c in t["caches"]))
    w("        kinds: [%s]," % ", ".join(str(k) for k in kinds))
    w("        have_argument: %d," % t["have_argument"])
    w("        extended_arg: %d," % t["extended_arg"])
    w("        cmp_op: &[%s]," % strs(t["cmp_op"]))
    w("    },")
w("];")
print("\n".join(out))
